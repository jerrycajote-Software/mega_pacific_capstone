// Map the current router pathname to its staff portal role identifier
export const getPortalRoleFromPathname = (pathname = '') => {
  const path = String(pathname || '').toLowerCase();
  if (path.startsWith('/sales') || path.startsWith('/sales-1megapacific')) return 'sales';
  if (path.startsWith('/finance') || path.startsWith('/finance-1megapacific')) return 'finance';
  if (path.startsWith('/logistic') || path.startsWith('/logistic-1megapacific')) return 'logistic';
  if (path.startsWith('/admin') || path.startsWith('/admin-1megapacific')) return 'admin';
  if (path.startsWith('/owner') || path.startsWith('/owner-1megapacific')) return 'owner';
  return null;
};
