// Returns an array of available provinces under CALABARZON
export const getAvailableProvinces = (regionName = CALABARZON_REGION.name) => {
  if (regionName === CALABARZON_REGION.name || !regionName) {
    return Object.keys(CALABARZON_REGION.provinces).sort();
  }
  return [];
};

// Returns an array of available cities/municipalities for a given province
export const getLocationsForProvince = (province) => {
  if (!province) return [];
  const provData = CALABARZON_REGION.provinces[province];
  if (provData && provData.cities) {
    return [...provData.cities].sort((a, b) => a.name.localeCompare(b.name));
  }
  return [];
};

// Returns the zip code for a given city/municipality within a province
export const getZipCodeForLocation = (province, locationName) => {
  if (!province || !locationName) return '';
  const provData = CALABARZON_REGION.provinces[province];
  if (provData && provData.cities) {
    const found = provData.cities.find(
      (c) => c.name.toLowerCase() === locationName.toLowerCase()
    );
    return found ? found.zipCode : '';
  }
  return '';
};

// Returns the list of barangays for a given city/municipality within a province
export const getBarangaysForLocation = (province, locationName) => {
  if (!province || !locationName) return [];
  const provData = CALABARZON_REGION.provinces[province];
  if (provData && provData.cities) {
    const found = provData.cities.find(
      (c) => c.name.toLowerCase() === locationName.toLowerCase()
    );
    return found && found.barangays ? [...found.barangays].sort() : [];
  }
  return [];
};
